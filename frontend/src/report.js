import { inr } from './api'
const esc = (s) => String(s ?? '').replace(/[&<>]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;' }[c]))

export function reportText(run) {
  const s = run.summary || {}, m = s.metrics || {}
  return `${s.headline || 'Run complete'}. ${s.narrative || ''} The crew placed ${m.po_placed || 0} purchase orders worth ${inr(m.po_value)} and informed ${m.emails_sent || 0} customers. ${m.still_late ? m.still_late + ' orders remain late and were escalated.' : ''}`
}

export function buildReportHTML(run) {
  const s = run.summary || {}, m = s.metrics || {}
  const acts = run.actions || []
  const plan = (run.events || []).find((e) => e.type === 'plan')?.data?.steps || []
  const row = (a) => {
    const p = a.payload || {}
    const what = a.type === 'PURCHASE_ORDER' ? `${p.qty} x ${p.product} from ${p.supplier} (${inr(p.total)})` : a.type === 'ORDER_UPDATE' ? `${p.order_id} · ${p.customer}: ${p.status}` : a.type === 'CUSTOMER_EMAIL' ? `Email to ${p.to}: ${p.subject}` : p.title
    return `<tr><td>${esc(a.type.replace('_', ' '))}</td><td>${esc(what)}</td><td>${esc(a.status.replace('_', ' '))}</td><td>${esc(a.reason)}</td></tr>`
  }
  return `<!doctype html><html><head><meta charset="utf-8"><title>OpsPilot Incident Report #${run.id}</title>
<style>body{font-family:Georgia,serif;color:#2b2824;max-width:820px;margin:40px auto;padding:0 24px;line-height:1.55}h1{font-weight:500;font-size:34px;margin:0}
.k{display:flex;gap:12px;flex-wrap:wrap;margin:22px 0}.k div{flex:1;min-width:140px;border:1px solid #bbb;padding:12px}.k b{display:block;font-size:24px;font-weight:500}
small,td,th{font-family:Arial,sans-serif;font-size:12px}table{border-collapse:collapse;width:100%}td,th{border-top:1px solid #ccc;padding:7px;text-align:left;vertical-align:top}
.tag{letter-spacing:.14em;text-transform:uppercase;font:11px Arial;color:#8d857a}</style></head><body>
<div class="tag">OpsPilot · Incident report #${run.id} · ${esc(new Date().toLocaleString())}</div><h1>${esc(s.headline || 'Incident report')}</h1>
<p><b>Incident:</b> ${esc(run.incident)}</p><p>${esc(s.narrative)}</p>
<div class="k"><div><small>Orders saved</small><b>${m.orders_protected ?? 0}</b></div><div><small>Revenue protected</small><b>${inr(m.revenue_protected)}</b></div><div><small>Manual work replaced</small><b>${((m.manual_minutes_saved || 0) / 60).toFixed(1)} h</b></div><div><small>Purchase orders</small><b>${m.po_placed ?? 0}</b></div></div>
${plan.length ? `<h3>Plan</h3><ol>${plan.map((x) => `<li>${esc(x)}</li>`).join('')}</ol>` : ''}
<h3>Actions and approvals (audit trail)</h3><table><tr><th>Type</th><th>Detail</th><th>Status</th><th>Guardian reason</th></tr>${acts.map(row).join('')}</table>
<h3>Next steps</h3><ul>${(s.next_steps || []).map((x) => `<li>${esc(x)}</li>`).join('')}</ul>
<p><small>Autonomy level: ${esc(s.autonomy || 'balanced')}. Generated by the OpsPilot agent crew. Risky actions were approved by a human.</small></p></body></html>`
}

export function downloadReport(run) {
  const blob = new Blob([buildReportHTML(run)], { type: 'text/html' })
  const a = document.createElement('a'); a.href = URL.createObjectURL(blob); a.download = `opspilot-report-run-${run.id}.html`
  document.body.appendChild(a); a.click(); a.remove()
}
